// Builds ../src/live-bundle.js (the admin Live tab: globe + page script) from live.ts, globe.ts and land.ts.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
const r = await build({ entryPoints: ['entry.ts'], bundle: true, minify: true, format: 'iife', target: 'es2020', legalComments: 'none', write: false });
const lic = readFileSync('node_modules/d3-geo/LICENSE', 'utf8').trim().split('\n').map((l) => ' * ' + l).join('\n');
const js = '/* Polaris Mail admin, Live tab. Includes d3-geo:\n' + lic + '\n */\n' + r.outputFiles[0].text;
writeFileSync('../src/live-bundle.js', '/* Generated by admin-live/build.mjs (npm run build in admin-live). Do not edit. */\nexport const LIVE_JS = ' + JSON.stringify(js) + ';\n');
console.log('live-bundle.js', js.length, 'bytes');
